"""
HL7 FHIR R4 export.

`to_fhir_bundle(analysis)` maps one analysis (the JSON returned by /api/analyse, after any edits
and re-computation) to a FHIR R4 Bundle of type "collection":

  * one DiagnosticReport (status "preliminary") whose conclusion is the generated impression and
    whose `result` references every Observation;
  * one Observation per liver observation (status "preliminary"): the LI-RADS category as
    valueCodeableConcept, the segment as bodySite, and components for size (UCUM mm), every
    feature state, the certainty envelope, decision-critical and the longitudinal comparison.

Identifiers are deterministic: urn:uuid values derived (uuid5) from the report, the impression
and the resource position, so the same analysis always yields the same bundle and every reference
resolves to a fullUrl inside it.

Terminology: concepts are identified by `code.text` plus local codes in the CodeSystem
"urn:radsenvelope:code". Only two HL7-defined category codes are used (diagnostic service section
RAD, observation category imaging). Mapping to standard terminologies such as LOINC, SNOMED CT and
RadLex is future work and is deliberately not attempted here, so no code is invented.
"""
from __future__ import annotations

import hashlib
import uuid

from radsenvelope.engine.ruleset import FEATURE_LABELS, FEATURES

LOCAL = "urn:radsenvelope:code"
UCUM = "http://unitsofmeasure.org"
HL7_SECTION = "http://terminology.hl7.org/CodeSystem/v2-0074"
HL7_OBS_CATEGORY = "http://terminology.hl7.org/CodeSystem/observation-category"
_NAMESPACE = uuid.UUID("6f1c3c52-6c2e-5b8e-9a51-2f0c9e1d4b7a")
DISCLAIMER = ("Decision support only. Generated by RADS-Envelope from the LI-RADS CT/MRI v2018 rule table; "
              "not a medical device. A radiologist confirms every category.")
STATUS_TEXT = {"defer": "Deferred to radiologist", "not_assignable": "Not assignable (size not documented)",
               "not_applicable": "LI-RADS not applicable (patient not at high risk)"}


def _local(code: str, text: str) -> dict:
    return {"coding": [{"system": LOCAL, "code": code, "display": text}], "text": text}


def _uuid(seed: str, name: str) -> str:
    return f"urn:uuid:{uuid.uuid5(_NAMESPACE, seed + '/' + name)}"


def _quantity(value: float, unit: str) -> dict:
    return {"value": value, "unit": unit, "system": UCUM, "code": unit}


def _component(code: str, text: str, **value) -> dict:
    return {"code": _local(code, text), **value}


def _longitudinal_components(lg: dict) -> list[dict]:
    comps = [_component("growth-comparison-rule", "Prior comparison rule", valueString=lg.get("rule") or ""),
             _component("growth-comparison", "Comparison with prior study",
                        valueString=lg.get("explanation") or "")]
    if lg.get("matching") in (None, "none"):
        return comps
    comps.append(_component("growth-computed", "Threshold growth computed from prior study",
                            valueCodeableConcept=_local(lg["growth_state"], lg["growth_state"].replace("_", " "))))
    if lg.get("prior_mm") is not None:
        comps.append(_component("prior-size", "Prior observation size", valueQuantity=_quantity(lg["prior_mm"], "mm")))
    if lg.get("percent_change") is not None:
        comps.append(_component("growth-percent", "Size change since prior",
                                valueQuantity=_quantity(lg["percent_change"], "%")))
    if lg.get("interval_days") is not None:
        comps.append(_component("growth-interval", "Interval since prior",
                                valueQuantity=_quantity(lg["interval_days"], "d")))
    if lg.get("prior_conflict"):
        comps.append(_component("prior-conflict", "Prior study disagrees with report", valueString=lg["prior_conflict"]))
    return comps


def _observation(o: dict, oid: str) -> dict:
    r = o["result"]
    assigned = r.get("status") == "assigned"
    value = (_local(r["acr_category"], r["acr_category"]) if assigned
             else _local(r.get("status", "unknown"), r.get("status", "unknown")))
    comps = []
    if o.get("size_mm") is not None:
        comps.append(_component("size", "Observation size", valueQuantity=_quantity(o["size_mm"], "mm")))
    else:
        comps.append(_component("size", "Observation size", dataAbsentReason={"text": "Size not documented"}))
    for k in FEATURES:
        state = (o.get("features") or {}).get(k, "not_documented")
        comps.append(_component(k, FEATURE_LABELS[k], valueCodeableConcept=_local(state, state.replace("_", " "))))
    if assigned:
        comps.append(_component("certainty-envelope", "Certainty envelope", valueString=", ".join(r["envelope"])))
    comps.append(_component("decision-critical", "Decision-critical uncertainty",
                            valueBoolean=bool(r.get("decision_critical"))))
    if not assigned:
        comps.append(_component("not-assigned-reason", STATUS_TEXT.get(r.get("status"), "Not assigned"),
                                valueString="; ".join(r.get("reasons", []))))
    if o.get("longitudinal"):
        comps += _longitudinal_components(o["longitudinal"])
    return {
        "resourceType": "Observation", "id": oid.removeprefix("urn:uuid:"), "status": "preliminary",
        "category": [{"coding": [{"system": HL7_OBS_CATEGORY, "code": "imaging", "display": "Imaging"}]}],
        "code": _local("lirads-category", "LI-RADS category"),
        "bodySite": {"text": o["label"]},
        "valueCodeableConcept": value,
        "component": comps,
        "note": [{"text": DISCLAIMER}],
    }


def to_fhir_bundle(analysis: dict) -> dict:
    """Map an analysis to a FHIR R4 collection Bundle. Pure and deterministic."""
    observations = analysis.get("observations") or []
    seed = hashlib.sha256(((analysis.get("report") or "") + "\x1f" + (analysis.get("impression") or ""))
                          .encode("utf-8")).hexdigest()
    obs_urls = [_uuid(seed, f"Observation/{i}") for i in range(len(observations))]
    report_url = _uuid(seed, "DiagnosticReport")
    report = {
        "resourceType": "DiagnosticReport", "id": report_url.removeprefix("urn:uuid:"), "status": "preliminary",
        "category": [{"coding": [{"system": HL7_SECTION, "code": "RAD", "display": "Radiology"}]}],
        "code": _local("lirads-assessment", f"{analysis.get('rules') or 'LI-RADS CT/MRI v2018'} assessment"),
        "result": [{"reference": u, "display": o["label"]} for u, o in zip(obs_urls, observations)],
        "conclusion": analysis.get("impression") or "",
    }
    entries = [{"fullUrl": report_url, "resource": report}]
    entries += [{"fullUrl": u, "resource": _observation(o, u)} for u, o in zip(obs_urls, observations)]
    return {"resourceType": "Bundle", "id": _uuid(seed, "Bundle").removeprefix("urn:uuid:"),
            "type": "collection", "entry": entries}
